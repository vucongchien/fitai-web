export function resolveZoneForMuscleId(id: MuscleId): MuscleZone {
  return MUSCLE_ZONE_MAP[id] ?? "neutral";
}

export function resolveMuscleIdsForGroup(name: string): readonly MuscleId[] {
  const normalized = name.trim().toLowerCase().replace(/[_-]+/g, " ");
  return DB_MUSCLE_TO_IDS[normalized] ?? [];
}

export function resolveGoalMuscleIds(groups: readonly string[]): Set<MuscleId> {
  const ids = new Set<MuscleId>();
  for (const group of groups) {
    for (const id of resolveMuscleIdsForGroup(group)) {
      ids.add(id);
    }
  }
  return ids;
}

export function formatMuscleLabel(name: string): string {
  return name
    .replace(/[_-]+/g, " ")
    .replace(/\b(left|right)\b/gi, "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

